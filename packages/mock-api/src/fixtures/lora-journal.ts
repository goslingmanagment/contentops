export function buildLoraJournal(people: readonly Person[]): JournalEvent[] {
  return [...OBJECT_HISTORY_ROWS, ACCEPT_SET_073, ...ROWS]
    .map(([date, time, actor, area, action, phrase, item, result], index) => ({
      id: `ev-lora-${String(index + 1).padStart(3, '0')}`,
      at: mskInstant(date, time),
      actor: actorOf(actor, people),
      area,
      action,
      phrase,
      item_id: item,
      thumb: item ? { key: item, ratio: '3:4' as const } : null,
      result: result ?? 'ok',
      changes: [...(CHANGES[`${date} ${time}`] ?? [])],
      request_id: `req-${date.replaceAll('-', '')}-${time.replace(':', '')}-${index}`,
    }))
    .sort((left, right) => right.at.localeCompare(left.at))
}

