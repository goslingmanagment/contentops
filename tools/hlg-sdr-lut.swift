// Generates packages/media/src/hlg-sdr-lut.ts: Apple's HLG → SDR conversion measured on a pattern
// of flat colours, no footage (SPEC §9.3, docs/reference/compression.md §10.12). Mac with FFmpeg:
//
//   swiftc -O tools/hlg-sdr-lut.swift -o /tmp/hlg-sdr-lut && /tmp/hlg-sdr-lut > packages/media/src/hlg-sdr-lut.ts
//
// Every RGB grid point of an HLG BT.2020 signal becomes a flat 8×8 block of a ProRes 4444 frame;
// AVFoundation decodes it to 16-bit RGB in SDR BT.709, and the middle of each block is one row of
// the table: 12-bit values as 3 hex digits, in the order of a .cube file (red runs fastest).
import AVFoundation
import CoreVideo
import Foundation

let points = 17
let block = 8
let perSide = 72  // 72² blocks ≥ 17³
let side = block * perSide
let dir = NSTemporaryDirectory() + "hlg-sdr-lut-\(getpid())/"
try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
defer { try? FileManager.default.removeItem(atPath: dir) }

// r, g, b of grid point `i` in .cube order.
func grid(_ i: Int) -> (Double, Double, Double) {
  let n = Double(points - 1)
  return (
    Double(i % points) / n, Double(i / points % points) / n, Double(i / (points * points)) / n
  )
}

// BT.2020 non-constant luminance, 10-bit limited range.
var planes = [[UInt16]](
  repeating: [UInt16](repeating: 0, count: side * side), count: 3)
for row in 0..<perSide {
  for col in 0..<perSide {
    let i = row * perSide + col
    let (r, g, b) = i < points * points * points ? grid(i) : (0, 0, 0)
    let y = 0.2627 * r + 0.6780 * g + 0.0593 * b
    let values = [
      64 + 876 * y, 512 + 896 * (b - y) / 1.8814, 512 + 896 * (r - y) / 1.4746,
    ]
    for (p, v) in values.enumerated() {
      for line in 0..<block {
        for x in 0..<block {
          planes[p][(row * block + line) * side + col * block + x] = UInt16(v.rounded())
        }
      }
    }
  }
}
let raw = dir + "pattern.yuv"
let movie = dir + "pattern.mov"
var bytes = Data()
for plane in planes { plane.withUnsafeBytes { bytes.append(contentsOf: $0) } }
try bytes.write(to: URL(fileURLWithPath: raw))

let ffmpeg = Process()
ffmpeg.executableURL = URL(fileURLWithPath: "/usr/bin/env")
let tags = [
  "-color_range", "tv", "-colorspace", "bt2020nc", "-color_primaries", "bt2020", "-color_trc",
  "arib-std-b67",
]
ffmpeg.arguments =
  ["ffmpeg", "-nostdin", "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "yuv444p10le", "-s"]
  + ["\(side)x\(side)", "-r", "30"] + tags
  + ["-i", raw, "-c:v", "prores_ks", "-profile:v", "4444xq", "-pix_fmt", "yuv444p10le"]
  + ["-qscale:v", "1", "-vendor", "apl0"] + tags + ["-movflags", "+write_colr", movie]
try ffmpeg.run()
ffmpeg.waitUntilExit()
guard ffmpeg.terminationStatus == 0 else { fatalError("ffmpeg failed") }

let asset = AVURLAsset(url: URL(fileURLWithPath: movie))
let reader = try AVAssetReader(asset: asset)
let output = AVAssetReaderTrackOutput(
  track: asset.tracks(withMediaType: .video)[0],
  outputSettings: [
    kCVPixelBufferPixelFormatTypeKey as String: kCVPixelFormatType_64RGBALE,
    AVVideoColorPropertiesKey: [
      AVVideoColorPrimariesKey: AVVideoColorPrimaries_ITU_R_709_2,
      AVVideoTransferFunctionKey: AVVideoTransferFunction_ITU_R_709_2,
      AVVideoYCbCrMatrixKey: AVVideoYCbCrMatrix_ITU_R_709_2,
    ],
  ])
reader.add(output)
reader.startReading()
guard let sample = output.copyNextSampleBuffer(), let image = CMSampleBufferGetImageBuffer(sample)
else { fatalError("no decoded frame: \(String(describing: reader.error))") }
CVPixelBufferLockBaseAddress(image, .readOnly)
let stride = CVPixelBufferGetBytesPerRow(image)
let base = CVPixelBufferGetBaseAddress(image)!

var hex = ""
for i in 0..<(points * points * points) {
  let row = i / perSide
  let col = i % perSide
  for channel in 0..<3 {
    var sum = 0.0
    for line in 2..<6 {
      for x in 2..<6 {
        let at = (row * block + line) * stride + (col * block + x) * 8 + channel * 2
        sum += Double(base.load(fromByteOffset: at, as: UInt16.self))
      }
    }
    hex += String(format: "%03x", Int((sum / 16 / 65535 * 4095).rounded()))
  }
}
CVPixelBufferUnlockBaseAddress(image, .readOnly)

print(
  """
  // Generated by tools/hlg-sdr-lut.swift, do not edit: Apple's HLG → SDR conversion measured on a
  // pattern of flat colours (SPEC §9.3, docs/reference/compression.md §10.12).
  export const HLG_SDR_LUT = {
    points: \(points),
    /** R, G, B of each grid point, 12 bits as 3 hex digits, in .cube order (red runs fastest). */
    values:
      '\(hex)',
  } as const
  """)
